#!/usr/bin/env python3
"""Export M0's S2 prompt set to committed files, for `stoke bench --serve`.

WHY THIS EXISTS. Gate item [2]'s bars (17.7 / 14.2 @ N=8/16, and 10.8 / 16.8)
are cells from M0's baseline table, measured over HTTP against ollama and
llama-server on the S2 scenario: 512 prompt tokens, 128 generated, N closed-loop
clients, no shared prefix. A bar is only a bar if the workload is the same one,
so the prompts are not re-invented here -- they are generated by importing the
EXISTING harness (`bench/scenarios.py`) and calling the same
`build_messages(S2, client_id)` the baselines were served, then writing the user
message's content verbatim.

`_WORDS` is calibrated so one word is exactly one BPE token in this model's
vocab; the per-client `[client N] ` prefix is M0's, and it is what keeps the N
prompts from being byte-identical to each other.

SALT: M0's measured runs passed a per-run salt to defeat prefix/prompt caching
between an engine's own repeat runs. `stoke bench --serve` has no cross-process
prompt cache (dedup is opt-in and off on this path), so the canonical salt=None
text is exported -- that is also the byte-exact form recorded in
`bench/scenarios.py`'s docstring. Cost: ~6 tokens of prefix that the salted
baselines also paid.

Usage: python tests/tooling/export_bench_prompts.py [--clients 16]
Writes tests/data/bench_prompts/s2-512-cNN.txt (one per client).
"""
import argparse
import pathlib
import sys

ROOT = pathlib.Path(__file__).resolve().parents[2]
sys.path.insert(0, str(ROOT / "bench"))

import scenarios  # noqa: E402  (path set above)


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--clients", type=int, default=16,
                    help="how many per-client prompts to export (N=16 is the "
                         "widest gate cell; --seqs 8 uses files 00..07)")
    args = ap.parse_args()

    # `scenarios.S2` is the locked family (N = 1/2/4/8/16). Any member gives
    # the prompt SHAPE -- prompt_tokens/max_tokens are identical across it and
    # only n_clients differs, and n_clients is not read here: the per-client
    # text depends only on client_id.
    s2 = scenarios.S2[0]
    assert s2.prompt_tokens == 512 and s2.max_tokens == 128 \
        and s2.shared_prefix_tokens == 0, \
        f"S2's shape moved since the bars were drawn: {s2}"

    out_dir = ROOT / "tests" / "data" / "bench_prompts"
    out_dir.mkdir(parents=True, exist_ok=True)

    for cid in range(args.clients):
        msgs = scenarios.build_messages(s2, client_id=cid, salt=None)
        assert len(msgs) == 1 and msgs[0]["role"] == "user", \
            "S2 has no shared prefix -- one user message is the whole prompt"
        text = msgs[0]["content"]
        path = out_dir / f"s2-512-c{cid:02d}.txt"
        # Binary write with no trailing newline: the driver reads the whole
        # file as the prompt, and a stray "\n" is a real token.
        path.write_bytes(text.encode("utf-8"))
        print(f"{path.name}: {len(text.split())} words, {len(text)} bytes")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
