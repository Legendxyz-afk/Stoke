#!/usr/bin/env python3
"""tests/data/make_fixtures.py -- generates tiny handcrafted GGUF v3 fixture
files consumed by tests/test_gguf.c. Run manually; output is committed
binary data (not regenerated by the build):

    python3 tests/data/make_fixtures.py

Layout per GGUF v3 (probed from the real 2.5GB Qwen3 model + the official
ggml gguf.md spec, verified byte-exact against both):

    header: magic[4]='GGUF', u32 version, u64 tensor_count, u64 metadata_kv_count
    metadata_kv_count x {
        u64 key_len; char key[key_len];         (NOT NUL-terminated)
        u32 value_type; <value per type>
    }
    tensor_count x {
        u64 name_len; char name[name_len];      (NOT NUL-terminated)
        u32 n_dims; u64 dims[n_dims];            (n_dims <= 4)
        u32 ggml_type; u64 offset;               (relative to data section start)
    }
    padding to `alignment` (default 32, general.alignment UINT32 overrides)
    tensor data section

Value-type widths: UINT8/INT8/BOOL=1, UINT16/INT16=2,
UINT32/INT32/FLOAT32=4, UINT64/INT64/FLOAT64=8, STRING=u64 len + bytes,
ARRAY=u32 elem_type + u64 count + count elements back-to-back.

ggml tensor type sizes used here (the only 3 verified against the real
file): F32=0 (blck=1,size=4), Q4_K=12 (blck=256,size=144), Q6_K=14
(blck=256,size=210).
"""
import os
import struct

# ---- GGUF value-type enum (A2) ----
T_UINT8 = 0
T_INT8 = 1
T_UINT16 = 2
T_INT16 = 3
T_UINT32 = 4
T_INT32 = 5
T_FLOAT32 = 6
T_BOOL = 7
T_STRING = 8
T_ARRAY = 9
T_UINT64 = 10
T_INT64 = 11
T_FLOAT64 = 12

# ---- ggml tensor-type enum (A4 -- only the 3 verified values) ----
GGML_F32 = 0
GGML_Q4_K = 12
GGML_Q6_K = 14

GGUF_MAGIC = b'GGUF'
GGUF_VERSION = 3

OUT_DIR = os.path.dirname(os.path.abspath(__file__))


class Writer:
    """Small byte-buffer builder for GGUF v3 bytes, little-endian throughout."""

    def __init__(self):
        self.buf = bytearray()

    def tell(self):
        return len(self.buf)

    def u8(self, v):
        self.buf += struct.pack('<B', v & 0xFF)

    def i8(self, v):
        self.buf += struct.pack('<b', v)

    def u16(self, v):
        self.buf += struct.pack('<H', v & 0xFFFF)

    def i16(self, v):
        self.buf += struct.pack('<h', v)

    def u32(self, v):
        self.buf += struct.pack('<I', v & 0xFFFFFFFF)

    def i32(self, v):
        self.buf += struct.pack('<i', v)

    def u64(self, v):
        self.buf += struct.pack('<Q', v & 0xFFFFFFFFFFFFFFFF)

    def i64(self, v):
        self.buf += struct.pack('<q', v)

    def f32(self, v):
        self.buf += struct.pack('<f', v)

    def f64(self, v):
        self.buf += struct.pack('<d', v)

    def raw(self, b):
        self.buf += bytes(b)

    def gstr_bytes(self, b):
        """length-prefixed byte string, no NUL (key/name/STRING-value encoding)."""
        self.u64(len(b))
        self.raw(b)

    def gstr(self, s):
        self.gstr_bytes(s.encode('utf-8'))

    # ---- header ----
    def header(self, tensor_count, kv_count):
        self.raw(GGUF_MAGIC)
        self.u32(GGUF_VERSION)
        self.u64(tensor_count)
        self.u64(kv_count)

    # ---- KV helpers: each writes key + value_type + value ----
    def kv_string(self, key, val):
        self.gstr(key)
        self.u32(T_STRING)
        self.gstr(val)

    def kv_u8(self, key, val):
        self.gstr(key); self.u32(T_UINT8); self.u8(val)

    def kv_i8(self, key, val):
        self.gstr(key); self.u32(T_INT8); self.i8(val)

    def kv_u16(self, key, val):
        self.gstr(key); self.u32(T_UINT16); self.u16(val)

    def kv_i16(self, key, val):
        self.gstr(key); self.u32(T_INT16); self.i16(val)

    def kv_u32(self, key, val):
        self.gstr(key); self.u32(T_UINT32); self.u32(val)

    def kv_i32(self, key, val):
        self.gstr(key); self.u32(T_INT32); self.i32(val)

    def kv_f32(self, key, val):
        self.gstr(key); self.u32(T_FLOAT32); self.f32(val)

    def kv_f64(self, key, val):
        self.gstr(key); self.u32(T_FLOAT64); self.f64(val)

    def kv_bool(self, key, val):
        self.gstr(key); self.u32(T_BOOL); self.u8(1 if val else 0)

    def kv_u64(self, key, val):
        self.gstr(key); self.u32(T_UINT64); self.u64(val)

    def kv_i64(self, key, val):
        self.gstr(key); self.u32(T_INT64); self.i64(val)

    def kv_array_str(self, key, vals):
        self.gstr(key)
        self.u32(T_ARRAY)
        self.u32(T_STRING)
        self.u64(len(vals))
        for v in vals:
            self.gstr(v)

    def kv_array_i32(self, key, vals):
        self.gstr(key)
        self.u32(T_ARRAY)
        self.u32(T_INT32)
        self.u64(len(vals))
        for v in vals:
            self.i32(v)

    # ---- tensor_info ----
    def tensor_info(self, name, dims, ggml_type, offset):
        self.gstr(name)
        self.u32(len(dims))
        for d in dims:
            self.u64(d)
        self.u32(ggml_type)
        self.u64(offset)


def pad_to(cur, align):
    return (align - (cur % align)) % align


def nbytes_f32(dims):
    n = 1
    for d in dims:
        n *= d
    return n * 4


def nbytes_q4k(dims):
    n = 1
    for d in dims:
        n *= d
    assert n % 256 == 0
    return (n // 256) * 144


def nbytes_q6k(dims):
    n = 1
    for d in dims:
        n *= d
    assert n % 256 == 0
    return (n // 256) * 210


def write_fixture(name, data):
    path = os.path.join(OUT_DIR, name)
    with open(path, 'wb') as f:
        f.write(data)
    print(f"wrote {path} ({len(data)} bytes)")


