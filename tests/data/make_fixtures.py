def make_tensor_data_exceeds_file():
    w = Writer()
    w.header(tensor_count=1, kv_count=0)
    # dims claim 100000 F32 elements (400000 bytes) but the file is tiny.
    w.tensor_info("t", [100000], GGML_F32, offset=0)
