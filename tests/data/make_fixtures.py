def make_bad_magic():
    w = Writer()
    w.raw(b'GGUX')  # wrong magic
    w.u32(GGUF_VERSION)
    w.u64(0)
    w.u64(0)
    return w.buf


def make_bad_version():
    w = Writer()
    w.raw(GGUF_MAGIC)
    w.u32(2)  # unsupported version
    w.u64(0)
    w.u64(0)
    return w.buf


def make_truncated_header():
    w = Writer()
    w.raw(GGUF_MAGIC)
    w.u32(GGUF_VERSION)
    w.raw(b'\x01\x02\x03')  # header cut off mid tensor_count (needs 24 bytes total)
    assert w.tell() < 24
    return w.buf


def make_kv_count_overflow():
    w = Writer()
    w.header(tensor_count=0, kv_count=0xFFFFFFFFFFFFFFFF)
    # No KV data follows -- count is implausible for a 24-byte file.
    return w.buf


def make_tensor_count_overflow():
    w = Writer()
    w.header(tensor_count=0xFFFFFFFFFFFFFFFF, kv_count=0)
    # No tensor_info data follows.
    return w.buf


def make_array_count_overflow():
    w = Writer()
    w.header(tensor_count=0, kv_count=1)
    w.gstr("a.i32")
    w.u32(T_ARRAY)
    w.u32(T_INT32)
    w.u64(0xFFFFFFFFFFFFFFFF)  # count -- would overflow count*width if unchecked
    # No element data follows.
    return w.buf


def make_misaligned_tensor():
    w = Writer()
    w.header(tensor_count=1, kv_count=0)
    w.tensor_info("t", [4], GGML_F32, offset=1)  # 1 % 32 != 0
    cur = w.tell()
    pad = pad_to(cur, 32)
    w.raw(b'\x00' * pad)
    w.raw(b'\x00' * 64)  # plenty of data; offset alignment is the only problem
    return w.buf


def make_string_len_exceeds_file():
    w = Writer()
    w.header(tensor_count=0, kv_count=1)
    w.gstr("k")             # valid 1-byte key
    w.u32(T_STRING)
    w.u64(0xFFFFFFFF)       # claimed string length -- file ends right after
    return w.buf


def make_key_len_exceeds_file():
    """Padded past metadata_kv_count's plausibility floor (13 bytes must
    remain per KV entry) so gguf_open() actually reaches parse_kv's
    key-length bounds check instead of getting rejected earlier by
    require_plausible_count. The original 32-byte version of this fixture
    (24-byte header + 8-byte key_len field = 8 remaining bytes, below the
    13-byte floor) never exercised the check it's named for -- confirmed
    empirically: it actually failed on metadata_kv_count, not key length."""
    w = Writer()
    w.header(tensor_count=0, kv_count=1)
    w.u64(0xFFFFFFFF)       # claimed key length -- file ends right after
    w.raw(b'\x00' * 16)     # padding: 24-byte header + 8-byte key_len + 16
                            # = 48 bytes, 24 remaining >= the 13-byte
                            # plausibility floor for kv_count=1
    return w.buf


def make_tensor_name_len_exceeds_file():
    """Padded past tensor_count's plausibility floor (24 bytes must remain
    per tensor_info entry) so gguf_open() actually reaches
    parse_tensor_info's name-length bounds check instead of getting
    rejected earlier by require_plausible_count. The original 32-byte
    version of this fixture (24-byte header + 8-byte name_len field = 8
    remaining bytes, below the 24-byte floor) never exercised the check
    it's named for -- confirmed empirically: it actually failed on
    tensor_count, not name length."""
    w = Writer()
    w.header(tensor_count=1, kv_count=0)
    w.u64(0xFFFFFFFF)       # claimed tensor name length -- file ends right after
    w.raw(b'\x00' * 32)     # padding: 24-byte header + 8-byte name_len + 32
                            # = 64 bytes, 40 remaining >= the 24-byte
                            # plausibility floor for tensor_count=1
    return w.buf


def make_n_dims_too_large():
    w = Writer()
    w.header(tensor_count=1, kv_count=0)
    w.gstr("t")
    w.u32(5)  # n_dims > 4
    for _ in range(5):
        w.u64(1)
    w.u32(GGML_F32)
    w.u64(0)
    return w.buf


def make_bad_value_type():
    w = Writer()
    w.header(tensor_count=0, kv_count=1)
    w.gstr("k")
    w.u32(13)  # outside 0..12
    w.u32(0)   # dummy payload, never reached if the check fires first
    return w.buf


