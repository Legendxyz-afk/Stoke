def make_valid_minimal():
    """Literal brief spec: 2 KV, 1 tensor, default alignment (key absent)."""
    w = Writer()
    w.header(tensor_count=1, kv_count=2)
    w.kv_string("general.architecture", "test")
    w.kv_u32("general.block_count", 4)
    w.tensor_info("weight", [4], GGML_F32, offset=0)
    cur = w.tell()
    pad = pad_to(cur, 32)  # default alignment, key absent
    w.raw(b'\x00' * pad)
    data_start = w.tell()
    assert data_start == cur + pad
    payload = bytes(range(16))  # nbytes = 4 elems * 4 bytes = 16, recognizable
    assert len(payload) == nbytes_f32([4])
    w.raw(payload)
    return w.buf


def make_valid_types():
    """0 tensors; one KV of every scalar/array kind the getters must handle."""
    w = Writer()
    kvs_written = []

    def track(fn, *args):
        fn(*args)
        kvs_written.append(args[0])

    w.header(tensor_count=0, kv_count=17)
    track(w.kv_string, "s.str", "hello")
    track(w.kv_u32, "s.u32", 42)
    track(w.kv_i32, "s.i32", -7)
    track(w.kv_u64, "s.u64", 123456789012)
    track(w.kv_u64, "s.u64_big", 0xFFFFFFFFFFFFFFFF)  # > INT64_MAX
    track(w.kv_i64, "s.i64", -123456789012)
    track(w.kv_f32, "s.f32", 3.5)
    track(w.kv_bool, "s.bool_t", True)
    track(w.kv_bool, "s.bool_f", False)
    track(w.kv_u8, "s.u8", 200)
    track(w.kv_i8, "s.i8", -100)
    track(w.kv_u16, "s.u16", 50000)
    track(w.kv_i16, "s.i16", -30000)
    track(w.kv_f64, "s.f64", 2.71828)
    track(w.kv_array_str, "a.str", ["alpha", "bravo", "charlie"])
    track(w.kv_array_i32, "a.i32", [10, -20, 30, -40])
    track(w.kv_array_str, "a.empty", [])
    assert len(kvs_written) == 17
    # 0 tensors -> data section is empty; file ends right after alignment pad.
    cur = w.tell()
    pad = pad_to(cur, 32)
    w.raw(b'\x00' * pad)
    return w.buf


def make_valid_multi_tensor():
    """Non-default alignment (16) + 3 tensors covering all 3 known ggml types,
    with a deliberate gap between tensor 1 and tensor 2 to prove the parser
    doesn't assume tight tiling (the format doesn't require it)."""
    w = Writer()
    w.header(tensor_count=3, kv_count=2)
    w.kv_string("general.architecture", "multi")
    w.kv_u32("general.alignment", 16)
    w.tensor_info("a", [16], GGML_F32, offset=0)      # nbytes=64
    w.tensor_info("b", [256], GGML_Q4_K, offset=64)   # nbytes=144, ends 208
    w.tensor_info("c", [256], GGML_Q6_K, offset=224)  # gap 208..224; nbytes=210, ends 434
    cur = w.tell()
    pad = pad_to(cur, 16)
    w.raw(b'\x00' * pad)
    data_start = w.tell()
    assert nbytes_f32([16]) == 64
    assert nbytes_q4k([256]) == 144
    assert nbytes_q6k([256]) == 210
    w.raw(bytes([0xAA]) * 64)     # tensor a
    w.raw(bytes([0xBB]) * 144)    # tensor b
    w.raw(bytes([0x00]) * 16)     # the gap (never read by any tensor)
    w.raw(bytes([0xCC]) * 210)    # tensor c
    assert w.tell() == data_start + 434
    return w.buf


