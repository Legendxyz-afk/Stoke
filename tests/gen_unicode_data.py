#!/usr/bin/env python3
"""tests/gen_unicode_data.py -- generates src/unicode_data.h: a compact,
sorted codepoint-range -> flags table covering 0x0..0x10FFFF, derived from
this Python's `unicodedata` module. The qwen2 pre-tokenizer regex
(src/tok.c) needs, per codepoint: is-letter (\\p{L}), is-number (\\p{N}),
is-whitespace (\\s). Committed generated output; regenerate with:

    python3 tests/gen_unicode_data.py

Flag derivation:
  LETTER     -- \\p{L}: unicodedata.category(chr(cp))[0] == 'L'
  NUMBER     -- \\p{N}: unicodedata.category(chr(cp))[0] == 'N'
  WHITESPACE -- \\s:    chr(cp).isspace() OR category in {Zs, Zl, Zp}
               (the isspace()/category union is belt-and-suspenders --
               Python's isspace() already covers Zs/Zl/Zp via bidirectional
               class, but both are checked explicitly rather than relying
               on that overlap holding forever)

A codepoint NOT covered by any emitted range has all flags 0 (letter=false,
number=false, whitespace=false) -- the common case, since most of
0x0..0x10FFFF is unassigned. Adjacent codepoints with identical flags are
merged into one range to keep the table compact (a few thousand ranges over
1.1M codepoints, instead of one entry per codepoint).

Unicode-version skew note: this generation was run under Python 3.14.2
(unicodedata Unicode 16.0.0). The oracle (llama-tokenize.exe, llama.cpp
b10037) may have been built against a different Unicode version, so a
handful of codepoints could disagree on category between this table and
the oracle's -- the byte-exact corpus golden (tests/tok_golden.sh and, for
full codespace coverage including unassigned codepoints,
tests/unicode_sweep_golden.sh) is the arbiter: any residual disagreement
surfaces as specific corpus lines failing, fixed by hand-adjusting just
those ranges.
"""
import sys
import unicodedata

FLAG_LETTER = 0x1
FLAG_NUMBER = 0x2
FLAG_WHITESPACE = 0x4

MAX_CP = 0x10FFFF

OUT_PATH = "src/unicode_data.h"


def flags_for(cp):
    ch = chr(cp)
    cat = unicodedata.category(ch)
    f = 0
    if cat[0] == 'L':
        f |= FLAG_LETTER
    if cat[0] == 'N':
        f |= FLAG_NUMBER
    if ch.isspace() or cat in ('Zs', 'Zl', 'Zp'):
        f |= FLAG_WHITESPACE
    return f


def build_ranges():
    ranges = []
    lo = 0
    cur = flags_for(0)
    for cp in range(1, MAX_CP + 1):
        f = flags_for(cp)
        if f != cur:
            if cur != 0:
                ranges.append((lo, cp - 1, cur))
            lo = cp
            cur = f
    if cur != 0:
        ranges.append((lo, MAX_CP, cur))
    return ranges


def flags_comment(f):
    parts = []
    if f & FLAG_LETTER:
        parts.append("L")
    if f & FLAG_NUMBER:
        parts.append("N")
    if f & FLAG_WHITESPACE:
        parts.append("WS")
    return "|".join(parts)


def main():
    ranges = build_ranges()
    uver = unicodedata.unidata_version
    pyver = sys.version.split()[0]

    lines = []
    lines.append("/* src/unicode_data.h -- GENERATED by tests/gen_unicode_data.py from")
    lines.append(" * Python's unicodedata. DO NOT EDIT BY HAND -- regenerate with:")
    lines.append(" *     python3 tests/gen_unicode_data.py")
    lines.append(" *")
    lines.append(f" * Generated against Python {pyver}, unicodedata (Unicode {uver}).")
    lines.append(" * See that script's docstring for the exact flag derivation and")
    lines.append(" * the corpus-gate-is-arbiter note re: Unicode-version skew against")
    lines.append(" * the llama.cpp b10037 oracle.")
    lines.append(" *")
    lines.append(" * Per-codepoint flags used by the qwen2 pre-tokenizer regex")
    lines.append(" * (src/tok.c): UNICODE_FLAG_LETTER (\\p{L}), UNICODE_FLAG_NUMBER")
    lines.append(" * (\\p{N}), UNICODE_FLAG_WHITESPACE (\\s). A codepoint not covered by")
    lines.append(" * any range below has all flags 0 (most of 0x0..0x10FFFF is")
    lines.append(" * unassigned). Requires common.h (u8/u32) already included by the")
    lines.append(" * includer -- see that header's own file comment for why.")
    lines.append(" */")
    lines.append("#ifndef STOKE_UNICODE_DATA_H")
    lines.append("#define STOKE_UNICODE_DATA_H")
    lines.append("")
    lines.append("#define UNICODE_FLAG_LETTER     0x1u")
    lines.append("#define UNICODE_FLAG_NUMBER     0x2u")
    lines.append("#define UNICODE_FLAG_WHITESPACE 0x4u")
    lines.append("")
    lines.append("typedef struct {")
    lines.append("    u32 lo;")
    lines.append("    u32 hi;")
    lines.append("    u8  flags;")
    lines.append("} UnicodeRange;")
    lines.append("")
    lines.append(f"/* {len(ranges)} ranges */")
    lines.append("static const UnicodeRange UNICODE_RANGES[] = {")
    for lo, hi, f in ranges:
        lines.append(f"    {{0x{lo:06X}, 0x{hi:06X}, {f}}}, /* {flags_comment(f)} */")
    lines.append("};")
    lines.append("")
    lines.append("#define UNICODE_RANGE_COUNT \\")
    lines.append("    ((u32)(sizeof(UNICODE_RANGES) / sizeof(UNICODE_RANGES[0])))")
    lines.append("")
    lines.append("/* Binary search over the sorted, non-overlapping ranges above.")
    lines.append(" * Returns 0 (no flags) for any codepoint not covered by a range,")
    lines.append(" * which includes the entire unassigned bulk of the codespace and")
    lines.append(" * any cp > 0x10FFFF a caller might (incorrectly) pass in. */")
    lines.append("static inline u8 unicode_cpt_flags(u32 cp) {")
    lines.append("    u32 lo = 0, hi = UNICODE_RANGE_COUNT;")
    lines.append("    while (lo < hi) {")
    lines.append("        u32 mid = lo + (hi - lo) / 2;")
    lines.append("        if (cp < UNICODE_RANGES[mid].lo) {")
    lines.append("            hi = mid;")
    lines.append("        } else if (cp > UNICODE_RANGES[mid].hi) {")
    lines.append("            lo = mid + 1;")
    lines.append("        } else {")
    lines.append("            return UNICODE_RANGES[mid].flags;")
    lines.append("        }")
    lines.append("    }")
    lines.append("    return 0;")
    lines.append("}")
    lines.append("")
    lines.append("#endif /* STOKE_UNICODE_DATA_H */")

    with open(OUT_PATH, "w", newline="\n") as f:
        f.write("\n".join(lines) + "\n")
    print(f"wrote {OUT_PATH}: {len(ranges)} ranges (Unicode {uver}, Python {pyver})")


if __name__ == "__main__":
    main()
